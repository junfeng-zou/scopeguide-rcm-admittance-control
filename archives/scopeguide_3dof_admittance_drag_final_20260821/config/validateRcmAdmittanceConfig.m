    if ~isfield(safety, names{index})
        error('scopeguide:config:MissingSafetyThreshold', ...
            'cfg.safety.%s is required.', names{index});
    end
    positiveScalar(safety.(names{index}), ['cfg.safety.', names{index}]);
end
if safety.FastForceWarningN >= safety.FastForceStopN || ...
        safety.FastMomentWarningNm >= safety.FastMomentStopNm
    error('scopeguide:config:InvalidSafetyThresholdOrder', ...
        'Fast warning thresholds must be smaller than stop thresholds.');
