function validateSafetyThresholds(safety)
names = {'RawForceStopN', 'RawMomentStopNm', ...
    'FastForceWarningN', 'FastForceStopN', ...
    'FastMomentWarningNm', 'FastMomentStopNm', ...
    'FastForceRateStopNSec'};
