end

function requireField(value, fieldName, parentName)
if ~isstruct(value) || ~isfield(value, fieldName)
    error('scopeguide:config:MissingField', ...
        '%s.%s is required.', parentName, fieldName);
end
end

function value = scalarString(inputValue, name)
value = string(inputValue);
if ~isscalar(value) || ismissing(value) || strlength(value) == 0
    error('scopeguide:config:InvalidString', ...
        '%s must be a nonempty scalar string.', name);
end
end

function value = optionalScalarString(inputValue, name)
value = string(inputValue);
if ~isscalar(value) || ismissing(value)
    error('scopeguide:config:InvalidString', ...
        '%s must be a scalar string.', name);
end
end

function logicalScalar(value, name)
if ~islogical(value) || ~isscalar(value)
    error('scopeguide:config:InvalidLogical', ...
        '%s must be a logical scalar.', name);
end
end

function positiveScalar(value, name)
if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || value <= 0
    error('scopeguide:config:InvalidPositiveScalar', ...
        '%s must be a finite positive scalar.', name);
end
end

function nonnegativeScalar(value, name)
if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || value < 0
    error('scopeguide:config:InvalidNonnegativeScalar', ...
        '%s must be a finite nonnegative scalar.', name);
end
end

function value = positiveFiniteVector(inputValue, count, name)
value = finiteVector(inputValue, count, name);
if any(value <= 0)
    error('scopeguide:config:InvalidPositiveVector', ...
        '%s must contain only positive values.', name);
end
end

function vector = finiteVector(value, count, name)
if ~isnumeric(value) || numel(value) ~= count || any(~isfinite(value(:)))
    error('scopeguide:config:InvalidVector', ...
        '%s must contain %d finite numeric values.', name, count);
end
vector = value(:);
end

function validateTransform(transform, name)
if ~isnumeric(transform) || ~isequal(size(transform), [4, 4]) || ...
        any(~isfinite(transform(:)))
    error('scopeguide:config:InvalidTransform', ...
        '%s must be a finite 4-by-4 numeric matrix.', name);
end
if norm(transform(4, :) - [0, 0, 0, 1], inf) > 1e-12
    error('scopeguide:config:InvalidTransform', ...
        '%s must have homogeneous bottom row [0 0 0 1].', name);
end
rotation = transform(1:3, 1:3);
if norm(rotation' * rotation - eye(3), 'fro') > 1e-10 || ...
        abs(det(rotation) - 1) > 1e-10
    error('scopeguide:config:InvalidTransform', ...
        '%s rotation must be right-handed and orthonormal.', name);
end
end

function validateRcmPoint(value)
if ~isnumeric(value) || numel(value) ~= 3
    error('scopeguide:config:InvalidRcmPoint', ...
        'rcm.PointBaseM must contain three numeric values.');
end
value = value(:);
if ~(all(isfinite(value)) || all(isnan(value)))
    error('scopeguide:config:InvalidRcmPoint', ...
        'rcm.PointBaseM must be fully finite or fully unknown (NaN).');
end
end
