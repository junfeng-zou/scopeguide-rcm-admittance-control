verifyError(testCase, @() run_servoj_communication_diagnostic( ...
    ArmPhysicalMotion=true, MotionConfirmation="wrong", ...
    FixtureAndClearanceConfirmed=true, SecondObserverPresent=true, ...
    ShowFigure=false, WriteResults=false), ...
    'scopeguide:servoJDiagnostic:ConfirmationMismatch');
end
